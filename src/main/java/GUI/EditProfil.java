    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
    if (txtNama.getText().trim().isEmpty()
                || txtEmail.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Nama dan Email tidak boleh kosong.");

            return;
        }

        User user = authService.getCurrentUser();

        user.setNamaLengkap(txtNama.getText().trim());
        user.setEmail(txtEmail.getText().trim());
        user.setPassword(String.valueOf(txtPassword.getPassword()));

        UserDAO dao = new UserDAO();

        if (dao.update(user)) {

            JOptionPane.showMessageDialog(this,
                    "Profil berhasil diperbarui.");

            // Refresh data pada halaman Pengaturan
            pengaturan.loadDataUser();

            dispose();

        } else {

            JOptionPane.showMessageDialog(this,
                    "Gagal memperbarui profil.");

        }
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void jCheckBox1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jCheckBox1ActionPerformed
    if (jCheckBox1.isSelected()) {
        txtPassword.setEchoChar((char) 0); // tampilkan password
    } else {
        txtPassword.setEchoChar(defaultEchoChar); // sembunyikan lagi
    }
    }//GEN-LAST:event_jCheckBox1ActionPerformed

